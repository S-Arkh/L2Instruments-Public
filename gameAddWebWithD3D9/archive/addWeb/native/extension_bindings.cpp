// x86 generator: can inspect the x86 extension even when Python is 64-bit.
#define WIN32_LEAN_AND_MEAN
#define NOMINMAX
#include <windows.h>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <set>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>
#include "extension_api.h"

namespace fs = std::filesystem;
using Count = DWORD (WINAPI*)();
using Get = BOOL (WINAPI*)(DWORD, l2ext::BindingInfo*, DWORD);
const char* typeName(l2ext::Type type) {
    switch (type) {
    case l2ext::Type::Void: return "void";
    case l2ext::Type::Byte: return "byte";
    case l2ext::Type::Int: return "int";
    case l2ext::Type::Bool: return "bool";
    case l2ext::Type::Float: return "float";
    case l2ext::Type::Int64: return "int64";
    case l2ext::Type::String: return "string";
    }
    return nullptr;
}
bool identifier(const std::string& s) {
    if (s.empty() || s.size() > 63) return false;
    for (size_t i = 0; i < s.size(); ++i) {
        const char c = s[i];
        if (!(c == '_' || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') ||
              (i && c >= '0' && c <= '9'))) return false;
    }
    return true;
}
std::string lower(std::string name) {
    for (char& c : name) if (c >= 'A' && c <= 'Z') c += 'a' - 'A';
    return name;
}

int wmain(int argc, wchar_t** argv) {
    if (argc != 3 && argc != 4) {
        std::fprintf(stderr, "Usage: extension_bindings.exe <ExtensionL2.dll> <ExtensionL2API.uc> [bindings.json]\n");
        return 2;
    }
    HMODULE module = nullptr;
    try {
        const auto dll = fs::canonical(argv[1]);
        module = LoadLibraryW(dll.c_str());
        if (!module) { std::fprintf(stderr, "Extension load failed: %lu\n", GetLastError()); return 3; }
        auto count = reinterpret_cast<Count>(GetProcAddress(module, "ExtensionL2Count"));
        auto get = reinterpret_cast<Get>(GetProcAddress(module, "ExtensionL2GetBinding"));
        if (!count || !get) throw std::runtime_error("Extension does not expose binding metadata");
        const auto size = count();
        if (!size || size > 4096) throw std::runtime_error("Invalid binding count");
        std::set<unsigned> indices;
        std::set<std::string> names;
        std::ostringstream uc, json;
        uc << "// Generated by extension_bindings. Edit src/extensionL2.cpp, then regenerate.\r\n"
           << "class ExtensionL2API extends Object;\r\n\r\n";
        json << "{\n  \"class\": \"ExtensionL2API\",\n  \"bindings\": [\n";
        for (DWORD i = 0; i < size; ++i) {
            l2ext::BindingInfo info{};
            if (!get(i, &info, sizeof(info)) || !info.name || !identifier(info.name) ||
                info.index < 256 || info.index >= 4096 || info.argumentCount > l2ext::MaxArguments ||
                !typeName(info.result)) throw std::runtime_error("Invalid binding descriptor");
            if (!indices.insert(info.index).second || !names.insert(lower(info.name)).second)
                throw std::runtime_error("Duplicate native index or UC function name");
            uc << "native(" << info.index << ") static final function ";
            if (info.result != l2ext::Type::Void) uc << typeName(info.result) << ' ';
            uc << info.name << '(';
            json << "    {\"index\": " << info.index << ", \"name\": \"" << info.name
                 << "\", \"return\": \"" << typeName(info.result) << "\", \"arguments\": [";
            for (unsigned j = 0; j < info.argumentCount; ++j) {
                const char* type = typeName(info.arguments[j]);
                if (!type || info.arguments[j] == l2ext::Type::Void)
                    throw std::runtime_error("Unsupported parameter type");
                if (j) { uc << ", "; json << ", "; }
                uc << type << " Arg" << j;
                json << '"' << type << '"';
            }
            uc << ");\r\n";
            json << "]}" << (i + 1 == size ? "\n" : ",\n");
        }
        json << "  ]\n}\n";
        const fs::path output = argv[2];
        if (fs::exists(output)) {
            std::ifstream old(output, std::ios::binary);
            std::string first;
            std::getline(old, first);
            if (first.find("// Generated by extension_bindings.") != 0)
                throw std::runtime_error("Refusing to replace a hand-written UC file");
        }
        if (!output.parent_path().empty()) fs::create_directories(output.parent_path());
        std::ofstream file(output, std::ios::binary | std::ios::trunc);
        file << uc.str();
        file.close();
        if (!file) throw std::runtime_error("Could not write UC declarations");
        if (argc == 4) {
            const fs::path path = argv[3];
            if (!path.parent_path().empty()) fs::create_directories(path.parent_path());
            std::ofstream manifest(path, std::ios::binary | std::ios::trunc);
            manifest << json.str();
            manifest.close();
            if (!manifest) throw std::runtime_error("Could not write bindings manifest");
        }
        std::printf("Generated %lu native declarations (Core.dll was not required).\n", size);
        FreeLibrary(module);
        return 0;
    } catch (const std::exception& error) {
        std::fprintf(stderr, "%s\n", error.what());
        if (module) FreeLibrary(module);
        return 4;
    }
}
